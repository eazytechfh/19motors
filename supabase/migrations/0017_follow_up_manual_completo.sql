create or replace function public.pipeline_etapas_set_updated_at()
returns trigger language plpgsql set search_path = public as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists trg_pipeline_etapas_updated_at on public.pipeline_etapas;
create trigger trg_pipeline_etapas_updated_at
before update on public.pipeline_etapas
for each row execute function public.pipeline_etapas_set_updated_at();

create or replace function public.pipeline_etapa_protegida(p_slug text)
returns boolean language sql immutable as $$
  select p_slug in (
    'oportunidade', 'em_qualificacao', 'em_negociacao',
    'follow_up', 'respondeu_follow_up', 'resgate'
  );
$$;

create or replace function public.bloquear_alteracao_etapa_protegida()
returns trigger language plpgsql set search_path = public as $$
begin
  if public.pipeline_etapa_protegida(old.slug) and row(
    new.slug, new.nome, new.cor, new.ordem, new.is_inicial
  ) is distinct from row(
    old.slug, old.nome, old.cor, old.ordem, old.is_inicial
  ) then
    raise exception 'Esta etapa é protegida por automações e não pode ser alterada.' using errcode = '42501';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_bloquear_alteracao_etapa_protegida on public.pipeline_etapas;
create trigger trg_bloquear_alteracao_etapa_protegida
before update on public.pipeline_etapas
for each row execute function public.bloquear_alteracao_etapa_protegida();

create or replace function public.impedir_exclusao_etapa_protegida()
returns trigger language plpgsql set search_path = public as $$
begin
  if public.pipeline_etapa_protegida(old.slug) then
    raise exception 'Esta etapa é protegida por automações e não pode ser excluída.' using errcode = '42501';
  end if;
  if exists (select 1 from public."BASE_DE_LEADS" where estagio_lead = old.slug) then
    raise exception 'Esta etapa possui leads. Mova-os antes de excluir.' using errcode = '23503';
  end if;
  return old;
end;
$$;

drop trigger if exists trg_impedir_exclusao_etapa_protegida on public.pipeline_etapas;
create trigger trg_impedir_exclusao_etapa_protegida
before delete on public.pipeline_etapas
for each row execute function public.impedir_exclusao_etapa_protegida();

-- A validação passa a usar pipeline_etapas em vez do CHECK estático conhecido.
do $$
declare constraint_row record;
begin
  for constraint_row in
    select c.conname
    from pg_constraint c
    join pg_class t on t.oid = c.conrelid
    join pg_namespace n on n.oid = t.relnamespace
    where n.nspname = 'public'
      and t.relname = 'BASE_DE_LEADS'
      and c.contype = 'c'
      and c.conname in (
        'BASE_DE_LEADS_estagio_lead_check',
        'base_de_leads_estagio_lead_check'
      )
  loop
    execute format('alter table public."BASE_DE_LEADS" drop constraint %I', constraint_row.conname);
  end loop;
end;
$$;

create or replace function public.validar_estagio_lead()
returns trigger language plpgsql set search_path = public as $$
begin
  if new.estagio_lead is null or not exists (
    select 1 from public.pipeline_etapas where slug = new.estagio_lead
  ) then
    raise exception 'Etapa do pipeline inexistente: %', coalesce(new.estagio_lead, '(vazia)') using errcode = '23503';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_validar_estagio_lead on public."BASE_DE_LEADS";
create trigger trg_validar_estagio_lead
before insert or update of estagio_lead on public."BASE_DE_LEADS"
for each row execute function public.validar_estagio_lead();

create or replace function public.sync_follow_manual_from_estagio()
returns trigger language plpgsql set search_path = public as $$
begin
  new.follow_manual := case
    when lower(coalesce(new.estagio_lead, '')) = 'follow_up' then 'ativo'
    else 'inativo'
  end;

  if new.estagio_lead = 'follow_up'
    and (tg_op = 'INSERT' or old.estagio_lead is distinct from new.estagio_lead)
  then
    new.ja_recebeu_msg := null;
    new.erro_follow_manual := null;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_sync_follow_manual_from_estagio on public."BASE_DE_LEADS";
create trigger trg_sync_follow_manual_from_estagio
before insert or update of estagio_lead, follow_manual on public."BASE_DE_LEADS"
for each row execute function public.sync_follow_manual_from_estagio();

