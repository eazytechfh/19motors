-- Etiquetas funcionais são resolvidas por nome; IDs variam entre instalações.
insert into public.etiquetas (nome, cor)
select values_to_insert.nome, values_to_insert.cor
from (values
  ('Número Inválido', '#000000'),
  ('follow 1', '#3b82f6'),
  ('follow 2', '#f4c51a')
) as values_to_insert(nome, cor)
where not exists (
  select 1 from public.etiquetas existing
  where lower(btrim(existing.nome)) = lower(btrim(values_to_insert.nome))
);

-- Compatibilidade com o workflow duplicado da Ale's Car. Nesse contrato, os
-- números 27, 28 e 29 são códigos semânticos gravados em BASE_DE_LEADS.etiquetas;
-- eles não são reutilizados como IDs reais no CRM-19-MOTORS.
create or replace function public.compatibilizar_etiquetas_workflow_ales()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  etiqueta_legada bigint;
  etiqueta_nome text;
  etiqueta_real_id bigint;
begin
  if new.etiquetas is null then
    return new;
  end if;

  delete from public.lead_etiquetas le
  using public.etiquetas e
  where le.id_lead = new.id
    and le.id_etiqueta = e.id
    and lower(btrim(e.nome)) in ('número inválido', 'follow 1', 'follow 2');

  foreach etiqueta_legada in array new.etiquetas loop
    etiqueta_nome := case etiqueta_legada
      when 27 then 'Número Inválido'
      when 28 then 'follow 1'
      when 29 then 'follow 2'
      else null
    end;

    if etiqueta_nome is not null then
      select id into etiqueta_real_id
      from public.etiquetas
      where lower(btrim(nome)) = lower(btrim(etiqueta_nome))
      order by id
      limit 1;

      if etiqueta_real_id is not null then
        insert into public.lead_etiquetas (id_lead, id_etiqueta)
        values (new.id, etiqueta_real_id)
        on conflict do nothing;
      end if;
    end if;
  end loop;

  return new;
end;
$$;

revoke all on function public.compatibilizar_etiquetas_workflow_ales() from public;

drop trigger if exists trg_compatibilizar_etiquetas_workflow_ales on public."BASE_DE_LEADS";
create trigger trg_compatibilizar_etiquetas_workflow_ales
after insert or update of etiquetas on public."BASE_DE_LEADS"
for each row execute function public.compatibilizar_etiquetas_workflow_ales();

-- Resposta real do cliente: tipos usuais do Chat Memory do n8n são human e user.
create or replace function public.mover_resposta_para_respondeu_follow_up()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.session_id is not null
    and lower(coalesce(new.message ->> 'type', '')) in ('human', 'user')
  then
    with movidos as (
      update public."BASE_DE_LEADS" l
      set estagio_lead = 'respondeu_follow_up'
      where regexp_replace(coalesce(l.telefone, ''), '[^0-9]', '', 'g') <> ''
        and regexp_replace(l.telefone, '[^0-9]', '', 'g') = regexp_replace(new.session_id::text, '[^0-9]', '', 'g')
        and l.estagio_lead = 'follow_up'
        and lower(coalesce(l.follow_manual, '')) = 'ativo'
        and l.id = (
          select candidate.id
          from public."BASE_DE_LEADS" candidate
          where regexp_replace(coalesce(candidate.telefone, ''), '[^0-9]', '', 'g') =
                regexp_replace(new.session_id::text, '[^0-9]', '', 'g')
            and candidate.estagio_lead = 'follow_up'
          order by candidate.id desc
          limit 1
        )
      returning l.id
    )
    insert into public.lead_historico_estagio (id_lead, estagio_anterior, estagio_novo, usuario)
    select id, 'follow_up', 'respondeu_follow_up', 'Sistema - resposta do cliente'
    from movidos;
  end if;
  return new;
end;
$$;

revoke all on function public.mover_resposta_para_respondeu_follow_up() from public;

drop trigger if exists trg_mover_resposta_para_respondeu_follow_up on public.dezenovemotors_chat_histories;
create trigger trg_mover_resposta_para_respondeu_follow_up
after insert or update of message, session_id on public.dezenovemotors_chat_histories
for each row execute function public.mover_resposta_para_respondeu_follow_up();

-- RPCs atômicas para o workflow; somente a service role pode executá-las.
create or replace function public.registrar_envio_follow_up(
  p_id_lead int4,
  p_estado text,
  p_etiqueta_nome text
) returns void language plpgsql security definer set search_path = public as $$
declare etiqueta_id bigint;
begin
  if p_estado not in ('sim', 'segundo_follow', '2º msg') then
    raise exception 'Estado de follow-up inválido.' using errcode = '22023';
  end if;

  update public."BASE_DE_LEADS"
  set ja_recebeu_msg = p_estado, erro_follow_manual = null
  where id = p_id_lead and estagio_lead = 'follow_up' and follow_manual = 'ativo';

  if not found then return; end if;

  select id into etiqueta_id from public.etiquetas
  where lower(btrim(nome)) = lower(btrim(p_etiqueta_nome)) order by id limit 1;
  if etiqueta_id is not null then
    insert into public.lead_etiquetas (id_lead, id_etiqueta)
    values (p_id_lead, etiqueta_id) on conflict do nothing;
  end if;
end;
$$;

create or replace function public.registrar_erro_follow_up(p_id_lead int4, p_erro text)
returns void language plpgsql security definer set search_path = public as $$
declare
  etiqueta_id bigint;
  v_numero_invalido boolean := lower(coalesce(p_erro, '')) like '%is not on whatsapp%'
    or lower(coalesce(p_erro, '')) like '%not registered%'
    or lower(coalesce(p_erro, '')) like '%invalid number%';
begin
  if v_numero_invalido then
    update public."BASE_DE_LEADS"
    set erro_follow_manual = left(coalesce(p_erro, 'erro'), 500),
        ja_recebeu_msg = 'erro',
        estagio_lead = 'resgate'
    where id = p_id_lead and estagio_lead = 'follow_up';

    if not found then return; end if;

    select id into etiqueta_id from public.etiquetas
    where lower(btrim(nome)) = lower('Número Inválido') order by id limit 1;
    if etiqueta_id is not null then
      insert into public.lead_etiquetas (id_lead, id_etiqueta)
      values (p_id_lead, etiqueta_id) on conflict do nothing;
    end if;

    insert into public.lead_historico_estagio (id_lead, estagio_anterior, estagio_novo, usuario)
    values (p_id_lead, 'follow_up', 'resgate', 'Sistema - número inválido no follow-up');
  else
    update public."BASE_DE_LEADS"
    set erro_follow_manual = left(coalesce(p_erro, 'erro transitório'), 500)
    where id = p_id_lead and estagio_lead = 'follow_up';
  end if;
end;
$$;

create or replace function public.encerrar_follow_up_sem_resposta(p_id_lead int4)
returns void language plpgsql security definer set search_path = public as $$
begin
  update public."BASE_DE_LEADS"
  set estagio_lead = 'resgate'
  where id = p_id_lead
    and estagio_lead = 'follow_up'
    and follow_manual = 'ativo'
    and ja_recebeu_msg in ('segundo_follow', '2º msg');

  if found then
    insert into public.lead_historico_estagio (id_lead, estagio_anterior, estagio_novo, usuario)
    values (p_id_lead, 'follow_up', 'resgate', 'Sistema - cadência encerrada sem resposta');
  end if;
end;
$$;

